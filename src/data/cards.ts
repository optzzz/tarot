function build(rows: Row[], suit: Suit): TarotCard[] {
  return rows.map(([id, name, en, upK, upM, revK, revM]) => ({
    id, name, en, suit,
    num: Number(id.slice(1)),
    up: { k: upK.split(' · '), m: upM },
    rev: { k: revK.split(' · '), m: revM },
  }));
}

